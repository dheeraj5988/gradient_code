export function demoCurriculum(courseId: string): Module[] {
  const titles = ["Getting started", "Core concepts", "Hands-on project", "Going to production"];
  return titles.map((t, mi) => ({
    id: `${courseId}-m${mi}`,
    title: t,
    order_index: mi,
    lessons: Array.from({ length: 4 }, (_, li) => ({
      id: `${courseId}-m${mi}-l${li}`,
      module_id: `${courseId}-m${mi}`,
      title: `${t}: Session ${li + 1}`,
      type: "video" as const,
      video_url: null,
      content_text: null,
      duration_seconds: 420 + li * 180,
      order_index: li,
      is_free_preview: mi === 0 && li === 0,
    })),
  }));
}

